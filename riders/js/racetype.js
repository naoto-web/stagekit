/* ===========================================================
   racetype.js — レース種別（予選／準決勝／決勝／一般…）の正規化
   ===========================================================
   🔑集計側（選手DB案件/実装/build_stats.js・Node）と画面側（detail.js・ブラウザ）の
     **両方がこの1本を読む**。正規化がずれると「出走表の種別」と「集計の種別」が
     噛み合わなくなるので、判定はここ以外に書かない。

   keirin.jp の `cls` は「Ａ級チ予選」「Ｓ級準々Ｂ」のように級班や開催の接頭辞が付く。
   直近4ヶ月で90種類あったが、Yが見たい軸は7つ（Naoto指定 9/23＋実データで選抜を追加）。

   実測（直近4ヶ月 2026/05/22〜09/22・全9,519レース／かっこ内はA3が出たレース数）：
     予選3,154(670) 一般2,239(537) 準決勝1,369(302) 特選935(0) 選抜798(311) 決勝616(125) 初特選349(0) その他59(1)

   ⚠️チャレンジ戦（A級3班）には特選・初特選が無い。代わりに「選抜」がある。
   ⚠️「その他」は賞レース・記念の冠名（Ｓ級特秀36／Ｓ級優秀6／白虎賞・青龍賞…16種類）。
     畳まずに出すと1走ずつの行が増えるだけなので、まとめている。

   判定の順序が大事（前のものほど優先）：
     初特選 → 特選 → 準決勝(準) → 決勝(決) → 予選(予) → 選抜 → 一般(般) → その他
     例：「Ａ級特予選」は特別予選＝予選／「Ｓ級準々Ｂ」＝準決勝／「Ｌ級ガ決Ａ」＝決勝 */
(function (root) {
  'use strict';

  /** 画面に出す行の順（2026-09-23 Naoto決定）＝**勝ち上がりのはしご順**。
      🔑上3つ（予選→準決勝→決勝）が勝ち上がりの順路。残りは走数の多い順に下へ。
      🔑**特選・初特選はA級3班に1レースも無い**（直近4ヶ月の実測＝特選935・初特選349レースは全てA級2班以上）
         ので、いちばん下に寄せてある＝いまの対象（A3）では常に空の行が下に来ない。
      ⚠️旧＝`一般・特選・初特選・選抜・予選・準決勝・決勝`。これは§21でNaotoが依頼文に書いた並びが
         そのまま残っていただけで、設計した順ではなかった（2026-09-23に付け替え）。
      ⚠️**集計側（build_stats.js）はこの順を使わない**（`byType` を種別名で引く連想配列にするだけ）。
         並べ替えているのは画面（detail.js の `typeRanks`）なので、順を変えても集計のやり直しは要らない。 */
  var RACE_TYPES = ['予選', '準決勝', '決勝', '一般', '選抜', '特選', '初特選', 'その他'];

  function raceTypeOf(cls) {
    var s = String(cls || '');
    if (!s) return 'その他';
    if (s.indexOf('初特選') >= 0) return '初特選';
    if (s.indexOf('特選') >= 0) return '特選';
    if (s.indexOf('準') >= 0) return '準決勝';     // 準決・準々・「Ｌ級東ガ準」（末尾が準）も拾う
    if (s.indexOf('決') >= 0) return '決勝';
    if (s.indexOf('予') >= 0) return '予選';
    if (s.indexOf('選抜') >= 0) return '選抜';
    if (s.indexOf('般') >= 0) return '一般';
    return 'その他';
  }

  /* ══════════ グレードレース（記念以上）の勝ち上がり ══════════
     2026-09-24 Naoto（えーすさんの要望）＝「G3（記念）の一次予選／二次予選／準決勝／決勝ごとに
     着順と決まり手が見たい」。

     🔴**グレード（G1/G2/G3）そのものはデータに無い**（2026-09-24に確認）。
        `keirin.sqlite` に grade 列は無く、生データのキャッシュ（kj・winticket・backfill）にも残っていない。
        競輪予想アプリ側も同じ結論に達している（`model/segment_probe.js`）。
        選手プロフィールには節ごとのグレード（`09/07 平Ｆ１`）があるが**直近8節ぶんだけ**＝
        2〜3ヶ月しか遡れず、集計の窓を埋められない。
     🔑**だから判定しない。**「一次予選／二次予選」という種別名は**記念以上でしか使われない**
        （F1・F2は単に「予選」）ので、〈一次予選がある開催〉で絞ればそれが記念以上になる。
        推測ではなく種別名そのものを読むので、誤判定しにくい。開催の判定は集計側（build_stats.js）。
     ⚠️**G1/G2/G3の内訳は出せない**＝まとめて「記念以上」として数える。
        実データ（2025/09〜2026/09）＝該当52開催・10,398走・909人。
     ⚠️取りこぼす開催が6つある＝グランプリ（平塚2025/12/28）・高松宮記念杯（岸和田2026/06/16＝
        東西予選制で「一予選」が無い）など、日程が特殊なG1。いずれもトップ層だけなので実害は小さい。
     ⚠️**記念以上にA級は出ない**（実測＝S2 690人／S1 277人／L1 57人／SS 14人・A級0人）
        ＝A級の選手を開くとこの枠は空になる。 */
  var GRADE_STAGES = ['一次予選', '二次予選', '準決勝', '決勝'];

  /** 記念以上の開催の中で、その `cls` が勝ち上がりのどの段階か。4つ以外（特選・一般・選抜…）は null。
      判定順＝一予 → 二予 → 準 → 決（前が優先）。
      ⚠️「Ｓ級特選予」は 予 を含むが 一予/二予 ではないので null（＝この表には出さない）。
      ⚠️「Ｓ級西二予」「Ｓ級東準決」のような東西別も拾える。 */
  function gradeStageOf(cls) {
    var s = String(cls || '');
    if (!s) return null;
    if (s.indexOf('一予') >= 0) return '一次予選';
    if (s.indexOf('二予') >= 0) return '二次予選';
    if (s.indexOf('準') >= 0) return '準決勝';
    if (s.indexOf('決') >= 0) return '決勝';
    return null;
  }

  var api = {
    raceTypeOf: raceTypeOf, RACE_TYPES: RACE_TYPES,
    gradeStageOf: gradeStageOf, GRADE_STAGES: GRADE_STAGES
  };
  if (typeof module !== 'undefined' && module.exports) module.exports = api;   // Node（build_stats.js）
  else root.RACETYPE = api;                                                     // ブラウザ
})(typeof globalThis !== 'undefined' ? globalThis : this);
