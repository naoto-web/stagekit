/* ===========================================================
   sw.js — 選手DBをホーム画面のアプリとして開けるようにするためだけのもの（要件§35・③PWA）
   ===========================================================
   🔴**何もキャッシュしない。** ネットワークにそのまま通す。
      理由＝この画面は `autoupdate.js` が版を見て自動更新する作りになっている（OBS案件§12）。
      Service Worker がファイルを抱えると、**新しい版を公開しても古い画面が出続ける**。
      「配信中に古い画面が出る」「直したのに直っていないように見える」はどちらも重い事故なので、
      速さやオフライン動作より **常に最新が出ること** を選ぶ。
   ⚠️オフラインでは動かないが、もともとGAS（ネット）が要るので変わらない。
   ⚠️将来キャッシュしたくなったら、**autoupdate.js との整合を先に決めてから**にする。

   スコープ＝この置き場所（`…/stagekit/riders/`）配下だけ。
   ⚠️OBSの出力ビューは同じ index.html を使うが、main.js が登録しないので影響しない。 */

self.addEventListener('install', function () {
  self.skipWaiting();            // 古いSWを待たずに入れ替える
});

self.addEventListener('activate', function (e) {
  e.waitUntil(self.clients.claim());
});

